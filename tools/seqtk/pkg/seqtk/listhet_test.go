package seqtk

import (
	"bytes"
	"strings"
	"testing"
)

func TestListHet_TableDriven(t *testing.T) {
	cases := []struct {
		name  string
		input string
		want  string
	}{
		{
			name:  "uppercase 2-base codes only",
			input: ">chr1\nACGTRYSWKM\n",
			want: "chr1\t5\tR\n" +
				"chr1\t6\tY\n" +
				"chr1\t7\tS\n" +
				"chr1\t8\tW\n" +
				"chr1\t9\tK\n" +
				"chr1\t10\tM\n",
		},
		{
			name: "3-/4-base codes (B/D/H/V/N) and ACGT are silently skipped",
			// Only R counts (popcount==2); the rest have popcount in
			// {1, 3, 4} which never equals 2.
			input: ">chr2\nACGTNBDHVR\n",
			want:  "chr2\t10\tR\n",
		},
		{
			name:  "lowercase IUPAC codes preserved as-is in output",
			input: ">low\nacgtryswkm\n",
			want: "low\t5\tr\n" +
				"low\t6\ty\n" +
				"low\t7\ts\n" +
				"low\t8\tw\n" +
				"low\t9\tk\n" +
				"low\t10\tm\n",
		},
		{
			name:  "no heterozygous bases => empty output",
			input: ">homo\nACGTACGT\n",
			want:  "",
		},
		{
			name:  "empty record emits nothing",
			input: ">empty\n\n",
			want:  "",
		},
		{
			name:  "mixed-case + ACGT interleaved; positions are 1-based",
			input: ">mix\nAaRrCcSsTt\n",
			want:  "mix\t3\tR\nmix\t4\tr\nmix\t7\tS\nmix\t8\ts\n",
		},
		{
			name: "multi-record stream",
			input: ">a\nACR\n" +
				">b\nACGT\n" +
				">c\nWWWW\n",
			want: "a\t3\tR\n" +
				"c\t1\tW\nc\t2\tW\nc\t3\tW\nc\t4\tW\n",
		},
	}

	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			var got bytes.Buffer
			if err := ListHet(strings.NewReader(tc.input), &got); err != nil {
				t.Fatalf("ListHet: %v", err)
			}
			if got.String() != tc.want {
				t.Fatalf("output mismatch.\nwant:\n%q\ngot:\n%q", tc.want, got.String())
			}
		})
	}
}

// TestListHet_ParityWithUpstream byte-compares the Go port against
// fixtures pre-generated by piping the matching input file through the
// upstream binary (reference_code/seqtk v1.5-r133).
func TestListHet_ParityWithUpstream(t *testing.T) {
	cases := []struct {
		name  string
		input string
		want  string
	}{
		{name: "ambig.fa", input: "ambig.fa", want: "listhet_ambig.expected.txt"},
		{name: "hety_basic.fa", input: "hety_basic.fa", want: "listhet_hety_basic.expected.txt"},
		{name: "hety_lowercase.fa", input: "hety_lowercase.fa", want: "listhet_hety_lowercase.expected.txt"},
		// small.fa has zero heterozygous bases, so this fixture is the
		// empty file — pins the "no output" path against upstream.
		{name: "small.fa (no hets)", input: "small.fa", want: "listhet_small.expected.txt"},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			in := readParityFile(t, tc.input)
			want := readParityFile(t, tc.want)
			var got bytes.Buffer
			if err := ListHet(bytes.NewReader(in), &got); err != nil {
				t.Fatalf("ListHet: %v", err)
			}
			mustEqualBytes(t, "listhet parity "+tc.name, got.Bytes(), want)
		})
	}
}
