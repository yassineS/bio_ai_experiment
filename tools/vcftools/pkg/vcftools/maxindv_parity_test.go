package vcftools

// Byte-for-byte parity tests for vcftools --max-indv (the random
// individual-downsample of variant_file_filters.cpp:filter_individuals_randomly).
//
// Upstream draws the kept subset with glibc srand()/rand() driving libstdc++'s
// std::random_shuffle, but seeds with srand(time(NULL)) and exposes NO seed
// flag — so a plain upstream run's chosen subset changes every wall-clock
// second and is not reproducible. (Verified empirically: running the upstream
// binary in consecutive seconds yields different #CHROM sample lists.)
//
// To make the selection both reproducible AND a faithful match for what
// upstream WOULD emit if seeded with the same value, this port ports glibc's
// exact rand() (glibc_rand.go) and the exact random_shuffle swap sequence, and
// exposes --max-indv-seed. The expected selections in
// testdata/parity/maxindv.expected were generated by a C harness that replays
// upstream's filter_individuals_randomly verbatim (same libstdc++
// std::random_shuffle, same glibc rand()) with srand(SEED) substituted for
// srand(time(NULL)); that harness was confirmed to match the real upstream
// vcftools binary when both used the same epoch-second seed.
//
// These tests t.Fatalf on any mismatch — there is no skip path.

import (
	"bufio"
	"os"
	"os/exec"
	"path/filepath"
	"runtime"
	"strconv"
	"strings"
	"testing"
)

// maxIndvCase is one (seed, maxN, expected kept samples) row from the fixture.
type maxIndvCase struct {
	seed int
	maxN int
	want []string
}

// loadMaxIndvFixture parses testdata/parity/maxindv.expected.
func loadMaxIndvFixture(t *testing.T) []maxIndvCase {
	t.Helper()
	f, err := os.Open(filepath.Join(vcftoolsFixtureDir(t), "maxindv.expected"))
	if err != nil {
		t.Fatalf("open fixture: %v", err)
	}
	defer f.Close()
	var cases []maxIndvCase
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		line := sc.Text()
		if strings.HasPrefix(line, "#") || strings.TrimSpace(line) == "" {
			continue
		}
		fields := strings.Split(line, "\t")
		if len(fields) != 3 {
			t.Fatalf("malformed fixture line %q", line)
		}
		seed, err := strconv.Atoi(fields[0])
		if err != nil {
			t.Fatalf("seed %q: %v", fields[0], err)
		}
		maxN, err := strconv.Atoi(fields[1])
		if err != nil {
			t.Fatalf("maxN %q: %v", fields[1], err)
		}
		cases = append(cases, maxIndvCase{seed: seed, maxN: maxN, want: strings.Split(fields[2], ",")})
	}
	if err := sc.Err(); err != nil {
		t.Fatalf("scan fixture: %v", err)
	}
	if len(cases) == 0 {
		t.Fatal("no fixture cases loaded")
	}
	return cases
}

// recodedSamples runs the port on maxindv.vcf with the given --max-indv N and
// --max-indv-seed seed, then returns the sample columns from the recoded
// #CHROM line (input order).
func recodedSamples(t *testing.T, maxN, seed int) []string {
	t.Helper()
	prefix := runVcftoolsParity(t, "maxindv.vcf", &Params{
		MaxIndv:        maxN,
		MaxIndvSet:     true,
		MaxIndvSeed:    seed,
		MaxIndvSeedSet: true,
		Recode:         true,
	})
	for _, ln := range readFileLines(t, prefix+".recode.vcf") {
		if strings.HasPrefix(ln, "#CHROM") {
			cols := strings.Split(ln, "\t")
			if len(cols) <= 9 {
				return nil
			}
			return cols[9:]
		}
	}
	t.Fatalf("no #CHROM line in recoded output")
	return nil
}

// TestParity_MaxIndv_Seeded asserts that --max-indv N --max-indv-seed S keeps
// exactly the sample subset that upstream's glibc rand()/random_shuffle picks
// for that seed, byte-for-byte (sample identity and order), for every fixture
// case.
func TestParity_MaxIndv_Seeded(t *testing.T) {
	for _, c := range loadMaxIndvFixture(t) {
		c := c
		t.Run("seed="+strconv.Itoa(c.seed)+"_max="+strconv.Itoa(c.maxN), func(t *testing.T) {
			got := recodedSamples(t, c.maxN, c.seed)
			if strings.Join(got, ",") != strings.Join(c.want, ",") {
				t.Fatalf("--max-indv %d --max-indv-seed %d:\n  got:  %v\n  want: %v",
					c.maxN, c.seed, got, c.want)
			}
		})
	}
}

// TestParity_MaxIndv_Seed0Equals1 pins the glibc quirk that srand(0) behaves
// like srand(1): both seeds must select the identical subset.
func TestParity_MaxIndv_Seed0Equals1(t *testing.T) {
	got0 := recodedSamples(t, 3, 0)
	got1 := recodedSamples(t, 3, 1)
	if strings.Join(got0, ",") != strings.Join(got1, ",") {
		t.Fatalf("srand(0) must equal srand(1): got0=%v got1=%v", got0, got1)
	}
}

// TestParity_MaxIndv_LiveUpstreamSeeded validates --max-indv --max-indv-seed
// byte-for-byte against the LIVE upstream binary by neutralising upstream's
// srand(time(NULL)) with an LD_PRELOAD shim that pins time() to a fixed value.
// Both tools then shuffle with the same glibc seed, so the recoded #CHROM
// sample list must match exactly. This is the strongest possible check of the
// glibc rand() + std::random_shuffle port; it requires a working C compiler
// and a Linux dynamic loader, and is skipped where those are unavailable.
func TestParity_MaxIndv_LiveUpstreamSeeded(t *testing.T) {
	if runtime.GOOS != "linux" {
		t.Skip("LD_PRELOAD time() shim requires Linux")
	}
	cc, err := exec.LookPath("gcc")
	if err != nil {
		if cc, err = exec.LookPath("cc"); err != nil {
			t.Skip("no C compiler available to build the time() shim")
		}
	}

	const seed = 1234567
	dir := t.TempDir()
	src := filepath.Join(dir, "faketime.c")
	so := filepath.Join(dir, "faketime.so")
	shim := "#include <time.h>\n" +
		"time_t time(time_t *t){time_t v=" + strconv.Itoa(seed) + ";if(t)*t=v;return v;}\n"
	if err := os.WriteFile(src, []byte(shim), 0o644); err != nil {
		t.Fatalf("write shim: %v", err)
	}
	if out, err := exec.Command(cc, "-shared", "-fPIC", "-o", so, src).CombinedOutput(); err != nil {
		t.Skipf("could not build time() shim (%v): %s", err, out)
	}

	bin := upstreamVcftools(t)
	vcf := fixtureVCF(t, "maxindv.vcf")

	for _, n := range []int{1, 2, 3} {
		n := n
		t.Run("max="+strconv.Itoa(n), func(t *testing.T) {
			// Upstream with srand(time()) pinned to the seed.
			upPrefix := filepath.Join(t.TempDir(), "up")
			cmd := exec.Command(bin, "--vcf", vcf, "--out", upPrefix, "--recode", "--max-indv", strconv.Itoa(n))
			cmd.Env = append(os.Environ(), "LD_PRELOAD="+so)
			if out, err := cmd.CombinedOutput(); err != nil {
				t.Fatalf("upstream run failed (%v):\n%s", err, out)
			}

			goPrefix := runGo(t, vcf, &Params{
				MaxIndv: n, MaxIndvSet: true,
				MaxIndvSeed: seed, MaxIndvSeedSet: true,
				Recode: true,
			})

			up := recodeSampleNames(t, upPrefix+".recode.vcf")
			got := recodeSampleNames(t, goPrefix+".recode.vcf")
			if strings.Join(got, ",") != strings.Join(up, ",") {
				t.Fatalf("--max-indv %d (seed %d): upstream kept %v, port kept %v", n, seed, up, got)
			}
		})
	}
}
