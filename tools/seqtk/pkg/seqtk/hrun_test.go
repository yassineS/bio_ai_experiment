package seqtk

import (
	"bytes"
	"strings"
	"testing"
)

func TestHrun_TableDriven(t *testing.T) {
	cases := []struct {
		name   string
		input  string
		minLen int
		want   string
	}{
		{
			// chr1 has runs of length 7 / 2 / 7 / 1 / 7 / 1 / 1 / 1 / 8.
			// With minLen=7 only the first three runs are emitted INSIDE
			// the loop; the final length-8 A-run is emitted by the
			// upstream "single-shot trailing flush" (mirrored here).
			name:   "basic min=7 with trailing flush at end of last record",
			input:  ">chr1\nAAAAAAACCGGGGGGGTAAAAAAATGCAAAAAAAA\n",
			minLen: 7,
			want:   "chr1\t0\t7\tA\nchr1\t9\t16\tG\nchr1\t17\t24\tA\nchr1\t27\t35\tA\n",
		},
		{
			name: "trailing flush uses LAST RECORD's name+state (upstream quirk)",
			// Two records. The first ends mid-run with l=6; that gets
			// overwritten by the start of chr2. chr2's tail is the only
			// run flushed by the post-loop `if`.
			input:  ">a\nAAAAAA\n>b\nCCCCCCCC\n",
			minLen: 7,
			// chr2's CCCCCCCC = length 8 -> flushed at end as `b 0 8 C`.
			// chr1's tail run (length 6) is silently dropped.
			want: "b\t0\t8\tC\n",
		},
		{
			name: "empty trailing record swallows the trailing flush (upstream UB)",
			// chr1's tail run is length 7 (= minLen). Upstream's
			// trailing-flush slot is overwritten by an empty record
			// because the empty record sets l=1 (reading the NUL
			// terminator at ks->seq.s[0]). With minLen=7, the flush
			// condition l(1) >= 7 is false → no output for chr1's tail.
			input:  ">chr1\nAAAAAAA\n>empty\n\n",
			minLen: 7,
			want:   "",
		},
		{
			name:   "case is NOT folded; AAaa is two runs of length 2",
			input:  ">m\nAAaa\n",
			minLen: 2,
			// Inside-loop emits the first AA run at the lowercase
			// boundary; the lowercase aa run is the open tail and
			// fires via the trailing flush.
			want: "m\t0\t2\tA\nm\t2\t4\ta\n",
		},
		{
			name:   "min=1 reports every run including length-1",
			input:  ">x\nACG\n",
			minLen: 1,
			want:   "x\t0\t1\tA\nx\t1\t2\tC\nx\t2\t3\tG\n",
		},
		{
			name:   "min greater than any run yields empty output",
			input:  ">x\nACGT\n",
			minLen: 5,
			want:   "",
		},
		{
			name:   "single all-same record uses trailing flush only",
			input:  ">homo\nNNNNNN\n",
			minLen: 3,
			want:   "homo\t0\t6\tN\n",
		},
		{
			name:   "completely empty input is a no-op",
			input:  "",
			minLen: 7,
			want:   "",
		},
	}

	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			var got bytes.Buffer
			if err := Hrun(strings.NewReader(tc.input), &got, HrunOptions{MinLen: tc.minLen}); err != nil {
				t.Fatalf("Hrun: %v", err)
			}
			if got.String() != tc.want {
				t.Fatalf("output mismatch.\nwant:\n%q\ngot:\n%q", tc.want, got.String())
			}
		})
	}
}

// TestHrun_TrailingFlushAcrossRecords pins the documented upstream
// "single-shot trailing flush" quirk (seqtk.c:1200). Without the carry
// of c/l/beg/name across the kseq_read loop, the last record's tail
// run is dropped — that would be a parity break vs upstream's binary.
func TestHrun_TrailingFlushAcrossRecords(t *testing.T) {
	// Three records, last ends with a flushable run. The first two
	// records have all of their qualifying runs reported inside the
	// loop; the last record's trailing run goes through the
	// post-loop flush.
	input := ">a\nAAAAAAACCC\n>b\nTTTTTTTTTT\n>c\nGGGGGGG\n"
	var got bytes.Buffer
	if err := Hrun(strings.NewReader(input), &got, HrunOptions{MinLen: 7}); err != nil {
		t.Fatalf("Hrun: %v", err)
	}
	// Trace: record a's 7-A run is emitted inside the loop when 'C'
	// is seen. Record b is all T's, so nothing is emitted inside b's
	// loop AND b's open run (10 T's) is overwritten by record c's
	// first iteration — that's the upstream bug we mirror, and is
	// observable in the upstream binary's output for this same input.
	// Record c's 7-G run survives via the post-loop trailing flush.
	want := "a\t0\t7\tA\nc\t0\t7\tG\n"
	if got.String() != want {
		t.Fatalf("trailing-flush across records: want %q, got %q", want, got.String())
	}
}

// TestHrun_ParityWithUpstream byte-compares the Go port against
// fixtures pre-generated by piping the matching input file through
// `reference_code/seqtk/seqtk hrun` (v1.5-r133).
func TestHrun_ParityWithUpstream(t *testing.T) {
	cases := []struct {
		name   string
		input  string
		want   string
		minLen int
	}{
		{
			name:   "nruns.fa default min=7",
			input:  "nruns.fa",
			want:   "hrun_nruns_default.expected.bed",
			minLen: 7,
		},
		{
			name:   "nruns.fa min=3",
			input:  "nruns.fa",
			want:   "hrun_nruns_l3.expected.bed",
			minLen: 3,
		},
		{
			name:   "nruns.fa min=2",
			input:  "nruns.fa",
			want:   "hrun_nruns_l2.expected.bed",
			minLen: 2,
		},
		{
			name:   "hety_basic.fa min=4",
			input:  "hety_basic.fa",
			want:   "hrun_hety_basic_l4.expected.bed",
			minLen: 4,
		},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			in := readParityFile(t, tc.input)
			want := readParityFile(t, tc.want)
			var got bytes.Buffer
			if err := Hrun(bytes.NewReader(in), &got, HrunOptions{MinLen: tc.minLen}); err != nil {
				t.Fatalf("Hrun: %v", err)
			}
			mustEqualBytes(t, "hrun parity "+tc.name, got.Bytes(), want)
		})
	}
}
