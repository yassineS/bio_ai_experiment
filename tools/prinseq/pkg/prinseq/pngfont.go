// pngfont.go provides a tiny hand-rolled 5x7 bitmap font for axis
// and legend labels in the PNG renderer. The repository sanctions
// only stdlib + gonum (+ the CRAM codec dep); `golang.org/x/image`
// is NOT available, so we cannot use `basicfont`. This font covers
// the glyphs the prinseq graphs need: digits, upper/lower letters,
